#!/usr/bin/env python3
"""Extract the kernel's 8x16 console font into a standalone C header.

Linux's lib/fonts/font_8x16.c carries the VGA console font under GPL-2.0; the
guest desktop needs a font and this avoids shipping a binary font blob that
nobody can rebuild.  Usage:

    scripts/extract-font.py build/kernel-arm64/linux-4.1.52 \
        userspace/desktop/font8x16.h
"""
import re
import sys

src = sys.argv[1] + "/lib/fonts/font_8x16.c"
dst = sys.argv[2]

text = open(src, errors="replace").read()
body = text.split("fontdata_8x16[FONTDATAMAX] = {", 1)[1].split("};", 1)[0]
body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
values = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", body)]
if len(values) != 4096:
    sys.exit(f"expected 4096 bytes, got {len(values)}")

with open(dst, "w") as f:
    f.write("/* Generated by scripts/extract-font.py from Linux 4.1.52\n")
    f.write(" * lib/fonts/font_8x16.c (GPL-2.0).  Do not edit. */\n")
    f.write("#ifndef LINUX41_FONT8X16_H\n#define LINUX41_FONT8X16_H\n\n")
    f.write("static const unsigned char font8x16[4096] = {\n")
    for i in range(0, 4096, 16):
        row = ", ".join(f"0x{v:02x}" for v in values[i:i + 16])
        f.write(f"    {row}, /* {i // 16:#04x} */\n")
    f.write("};\n\n#endif\n")
print(f"wrote {dst} ({len(values)} bytes)")
